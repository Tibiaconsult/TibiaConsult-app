export type Element = "fire" | "energy" | "death" | "ice" | "earth" | "physical" | "holy";

export type SecondaryGroup =
  | "great-beams"
  | "special"
  | "ultimate-strikes"
  | "focus"
  | "stance"
  | "crippling";

export interface Spell {
  id: string;
  name: string;
  words: string;
  level: number;
  mana: number;
  base: number | null;
  element: Element | null;
  /** Cooldown individual em segundos */
  cooldown: number;
  /** Tempo que trava o grupo de ataque (2 s normal, 4 s para Focus) */
  attackLock: number;
  secondary?: { group: SecondaryGroup; cooldown: number };
  kind: "spell" | "rune";
  area: string;
  notes?: string;
}

